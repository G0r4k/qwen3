import JSZip from 'jszip';
import { saveAs } from 'file-saver';
import { FileNode } from '../types';

function flattenFiles(nodes: FileNode[], path: string = ''): { path: string; content: string }[] {
  const result: { path: string; content: string }[] = [];

  for (const node of nodes) {
    const currentPath = path ? `${path}/${node.name}` : node.name;
    
    if (node.type === 'file' && node.content !== undefined) {
      result.push({ path: currentPath, content: node.content });
    } else if (node.type === 'folder' && node.children) {
      result.push(...flattenFiles(node.children, currentPath));
    }
  }

  return result;
}

export async function exportProjectAsZip(files: FileNode[], projectName: string = 'my-project') {
  const zip = new JSZip();
  const flatFiles = flattenFiles(files);

  // Add all project files
  for (const file of flatFiles) {
    zip.file(file.path, file.content);
  }

  // Add a README for the exported project
  const readme = `# ${projectName}

Exported from LocalCoder - AI-Powered IDE

## Files included:
${flatFiles.map(f => `- ${f.path}`).join('\n')}

## Generated by:
- Director Model: qwen2.5-coder:3b
- Executor Model: qwen2.5-coder:3b
- Date: ${new Date().toLocaleString()}
`;
  zip.file('EXPORT_INFO.md', readme);

  // Generate and download
  const blob = await zip.generateAsync({ type: 'blob' });
  saveAs(blob, `${projectName}.zip`);
}

export async function exportSingleFile(content: string, filename: string) {
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  saveAs(blob, filename);
}
